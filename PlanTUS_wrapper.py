weight_skin_target_distances = config["weight_skin_target_distances"]
weight_skin_target_angles = config["weight_skin_target_angles"]
weight_skin_target_intersections = config["weight_skin_target_intersections"]
weight_skin_skull_angles = config["weight_skin_skull_angles"]
weight_skull_thickness = config["weight_skull_thickness"]

# PlanTUS paths ----------------------------------------------------------------
plantus_main_folder = str(resource_path())
plantus_code_path = os.path.join(plantus_main_folder, "code")
