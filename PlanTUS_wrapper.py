"""
PlanTUS wrapper script
======================
This script orchestrates the PlanTUS pipeline using the functions in
`PlanTUS.py`. Its inputs are the subject-specific data paths and device
parameters near the top of the file.

Usage
-----
1. Fill in the *Subject-specific variables* and *Transducer-specific
   variables* below.
2. Run this script with Python 3.

Outputs
-------
All outputs are written into `<m2m_subject>/PlanTUS/<ROI-name>/` and
include surfaces (`*.surf.gii`/`*.stl`) and per-vertex metrics
(`*.func.gii`).


(c) Maximilian Lueckel, mlueckel@uni-mainz.de
"""
